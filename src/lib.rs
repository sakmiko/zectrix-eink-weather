fn measure_str_7x11(text: &str, gap: i32) -> i32 {
    let mut w = 0_i32;
    let chars: Vec<char> = text.chars().collect();
    for (i, ch) in chars.iter().enumerate() {
        w += if *ch == ' ' {
            4
        } else if let Some((gw, _)) = glyph_7x11(*ch) {
            gw as i32
        } else {
            6
        };
        if i + 1 < chars.len() {
            w += gap;
        }
    }
    w
}

fn draw_str_7x11(
    disp: &mut FrameDisplay,
    text: &str,
    x: i32,
    y: i32,
    on: bool,
    gap: i32,
    align: TextAlign,
) -> i32 {
    if text.is_empty() {
        return 0;
    }
    let tw = measure_str_7x11(text, gap);
    let mut cx = match align {
        TextAlign::Left => x,
        TextAlign::Center => x - tw / 2,
        TextAlign::Right => x - tw,
    };
    for ch in text.chars() {
        if ch == ' ' {
            cx += 4 + gap;
            continue;
        }
        if let Some((gw, rows)) = glyph_7x11(ch) {
            for (ry, bits) in rows.iter().enumerate() {
                for rx in 0..(gw as i32) {
                    if ((bits >> ((gw as i32) - 1 - rx)) & 1) == 1 {
                        disp.draw_pixel(cx + rx, y + (ry as i32), on);
                    }
                }
            }
            cx += (gw as i32) + gap;
        } else {
            draw_micro_5x7(disp, &ch.to_string(), cx, y + 2, on, 1, TextAlign::Left);
            cx += 6 + gap;
        }
    }
    tw
}

