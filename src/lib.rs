/// 全量环境驱动的画面排版与视觉风格配置（可通过 `.env` 或环境变量动态控制）
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct WeatherRenderConfig {
    pub previous_frame_hash: Option<String>,
    pub header_badge: String,
    pub trend_badge: String,
    pub trend_title: String,
    pub label_feels_like: String,
    pub label_humidity: String,
    pub label_aqi: String,
    pub margin_px: i32,
    pub card_border_px: u32,
    pub card_shadow_px: u32,
    pub hero_temp_shadow: bool,
    pub invert_masthead: bool,
    pub invert_today_header: bool,
    pub forecast_days: usize,
    pub hourly_points: usize,
}

impl Default for WeatherRenderConfig {
    fn default() -> Self {
        Self::from_env()
    }
}

impl WeatherRenderConfig {
    pub fn from_env() -> Self {
        load_dotenv_if_present();
        Self {
            previous_frame_hash: None,
            header_badge: env_or("WEATHER_HEADER_BADGE", "气象站"),
            trend_badge: env_or("WEATHER_TREND_BADGE", "24H"),
            trend_title: env_or("WEATHER_TREND_TITLE", "趋势"),
            label_feels_like: env_or("WEATHER_LABEL_FEELS", "体感"),
            label_humidity: env_or("WEATHER_LABEL_HUMIDITY", "湿度"),
            label_aqi: env_or("WEATHER_LABEL_AQI", "空气"),
            margin_px: env_parse("WEATHER_MARGIN_PX", 4_i32).clamp(2, 8),
            card_border_px: env_parse("WEATHER_CARD_BORDER_PX", 2_u32).clamp(1, 3),
            card_shadow_px: env_parse("WEATHER_CARD_SHADOW_PX", 2_u32).clamp(0, 4),
            hero_temp_shadow: env_bool("WEATHER_HERO_TEMP_SHADOW", true),
            invert_masthead: env_bool("WEATHER_INVERT_MASTHEAD", true),
            invert_today_header: env_bool("WEATHER_INVERT_TODAY_HEADER", true),
            forecast_days: env_parse("WEATHER_FORECAST_DAYS", 4_usize).clamp(3, 5),
            hourly_points: env_parse("WEATHER_HOURLY_POINTS", 5_usize).clamp(3, 7),
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum PublishDecision {
    Publish,
    Unchanged,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct MonochromeFrame {
    pub width: u32,
    pub height: u32,
    pub pixels: Vec<u8>,
    pub sha256: String,
}

impl MonochromeFrame {
    pub fn png_bytes(&self) -> Result<Vec<u8>, WeatherRenderError> {
        let image = GrayImage::from_raw(self.width, self.height, self.pixels.clone())
            .ok_or(WeatherRenderError::InvalidFrame)?;
        let mut output = Cursor::new(Vec::new());
        image::DynamicImage::ImageLuma8(image)
            .write_to(&mut output, image::ImageFormat::Png)
            .map_err(WeatherRenderError::Image)?;
        Ok(output.into_inner())
    }

    pub fn write_png(&self, path: impl AsRef<Path>) -> Result<(), WeatherRenderError> {
        std::fs::write(path, self.png_bytes()?)
            .map_err(image::ImageError::IoError)
            .map_err(WeatherRenderError::Image)?;
        Ok(())
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct WeatherRenderOutput {
    pub snapshot: WeatherSnapshot,
    pub frame: MonochromeFrame,
    pub visible_text: Vec<String>,
    pub publish_decision: PublishDecision,
}

#[derive(Debug, Error)]
pub enum WeatherRenderError {
    #[error("画布尺寸无效")]
    InvalidFrame,
    #[error("写入或编码 PNG 失败：{0}")]
    Image(#[source] image::ImageError),
}

#[derive(Clone, Copy, Eq, PartialEq)]
enum TextAlign {
    Left,
    Center,
    Right,
}

pub fn render_weather_dashboard(
    snapshot: WeatherSnapshot,
    config: WeatherRenderConfig,
) -> Result<WeatherRenderOutput, WeatherRenderError> {
    let (pixels, visible_text) = draw_gallery_weather_station(&snapshot, &config);
    let sha256 = format!("{:x}", Sha256::digest(&pixels));
    let publish_decision = if config.previous_frame_hash.as_deref() == Some(&sha256) {
        PublishDecision::Unchanged
    } else {
        PublishDecision::Publish
    };

    Ok(WeatherRenderOutput {
        snapshot,
        frame: MonochromeFrame {
            width: DISPLAY_WIDTH,
            height: DISPLAY_HEIGHT,
            pixels,
            sha256,
        },
        visible_text,
        publish_decision,
    })
}

/// V3「画廊级高对比分栏卡片风 (Gallery Card HUD)」渲染引擎：
/// - 顶栏隐藏数据来源标签，纯粹展示 [气象站] + 16×16 城市·区县（如 北京 · 海淀区）+ 预警/空气胶囊 + 更新时间
/// - 采用 16×16 主字库（含 88 区县完整字集）+ 12×12 辅助字库 + 7×11 圆润数字字库
/// - 采用 52×52 双层网点主天气插画 + 24×24 像素级重绘小图标
fn draw_gallery_weather_station(
    scene: &WeatherSnapshot,
    cfg: &WeatherRenderConfig,
) -> (Vec<u8>, Vec<String>) {
    let mut disp = FrameDisplay::new();
    let mut visible = Vec::new();
    let m = cfg.margin_px;
    let full_w = (DISPLAY_WIDTH as i32 - 2 * m) as u32;

    // =========================================================================
    // ZONE 1: TOP INVERTED MASTHEAD CARD (X: m..400-m, Y: 4..32, H: 28px)
    // =========================================================================
    if cfg.invert_masthead {
        disp.fill_rect(m, 4, full_w, 28, true);
        for (cx, cy) in [
            (m, 4),
            (m + full_w as i32 - 1, 4),
            (m, 31),
            (m + full_w as i32 - 1, 31),
        ] {
            disp.draw_pixel(cx, cy, false);
        }
    } else {
        disp.draw_chamfer_card(m, 4, full_w, 28, cfg.card_border_px, 0);
    }
    let mast_fg = !cfg.invert_masthead;

    // Left Stamp Pill: [ 气象站 ]
    let bw = (measure_cjk_12(&cfg.header_badge, 1) + 10).max(40) as u32;
    disp.draw_pill(m + 4, 8, bw, 20, true, cfg.invert_masthead);
    draw_cjk_12x12(
        &mut disp,
        &cfg.header_badge,
        m + 4 + (bw as i32) / 2,
        12,
        !mast_fg,
        TextAlign::Center,
        1,
    );

    // 16x16 City & District Title (Pure Location Display without Source Badge)
    let cx_loc = m + 4 + (bw as i32) + 8;
    let w_city = draw_cjk_16x16(&mut disp, &scene.city, cx_loc, 10, mast_fg, TextAlign::Left, 2);
    if !scene.district.is_empty() && scene.district != scene.city {
        let dot_x = cx_loc + w_city + 5;
        disp.fill_rect(dot_x, 17, 2, 2, mast_fg);
        draw_cjk_16x16(
            &mut disp,
            &scene.district,
            dot_x + 7,
            10,
            mast_fg,
            TextAlign::Left,
            2,
        );
        visible.push(format!("{} · {}", scene.city, scene.district));
    } else {
        visible.push(scene.city.clone());
    }

    // Right Timestamp + Alert/AQI Pill
    let time_str = format!("{} P{}", scene.updated_at, scene.page_id);
    let time_w = (time_str.len() as i32) * 6;
    draw_micro_5x7(&mut disp, &time_str, 396 - m, 15, mast_fg, 1, TextAlign::Right);
    let sep_x = 396 - m - time_w - 6;
    disp.fill_rect(sep_x, 10, 1, 16, mast_fg);

    if let Some(alert_text) = scene.alert.as_deref() {
        let al_txt = format!("! {alert_text}");
        let al_w = (measure_cjk_12(&al_txt, 1) + 10) as u32;
        let al_x = sep_x - 6 - (al_w as i32);
        disp.draw_pill(al_x, 8, al_w, 20, true, cfg.invert_masthead);
        draw_cjk_12x12(
            &mut disp,
            &al_txt,
            al_x + (al_w as i32) / 2,
            12,
            !mast_fg,
            TextAlign::Center,
            1,
        );
        visible.push(alert_text.to_owned());
    } else {
        let aq_txt = format!("{} {}", scene.aqi_badge, scene.aqi);
        let aq_w = (measure_cjk_12(&aq_txt, 1) + 10) as u32;
        let aq_x = sep_x - 6 - (aq_w as i32);
        disp.draw_pill(aq_x, 9, aq_w, 18, false, cfg.invert_masthead);
        draw_cjk_12x12(
            &mut disp,
            &aq_txt,
            aq_x + (aq_w as i32) / 2,
            12,
            mast_fg,
            TextAlign::Center,
            1,
        );
    }

    // =========================================================================
    // ZONE 2: MIDDLE SPLIT DECK (Y: 37..193, H: 156px)
    // =========================================================================
    // --- Left Card: Live Weather Hero (X: 4, Y: 37, W: 188, H: 156) ---
    disp.draw_chamfer_card(4, 37, 188, 156, cfg.card_border_px, cfg.card_shadow_px);

    // 52x52 Pixel-Art Hero Weather Illustration at (14, 46)
    draw_hero_weather_icon_52(&mut disp, scene.hero_icon, 14, 46);

    // Hero Temperature at (76, 46)
    let t_str = scene.temp_c.to_string();
    let (dw_t, dh_t, dt_t, gap_t) = if t_str.len() <= 2 {
        (22_u32, 38_u32, 5_u32, 4_i32)
    } else {
        (17_u32, 38_u32, 4_u32, 3_i32)
    };
    let tw_num = draw_hero_temp_str(&mut disp, &t_str, -300, -300, dw_t, dh_t, dt_t, gap_t, false);
    draw_hero_temp_str(
        &mut disp,
        &t_str,
        76,
        46,
        dw_t,
        dh_t,
        dt_t,
        gap_t,
        cfg.hero_temp_shadow,
    );
    let ux = 76 + tw_num + 5;
    draw_str_7x11(&mut disp, "°C", ux, 48, true, 1, TextAlign::Left);
    draw_str_7x11(
        &mut disp,
        &format!("{}~{}°", scene.low_c, scene.high_c),
        ux,
        70,
        true,
        1,
        TextAlign::Left,
    );
    visible.push(format!("{}°C", scene.temp_c));

    // 16x16 Primary Condition Title + Sub-metric at Y: 100
    draw_cjk_16x16(&mut disp, &scene.condition, 16, 100, true, TextAlign::Left, 2);
    visible.push(scene.condition.clone());
    let sub_str = format!("{} {}", scene.hero_sub_cn, scene.hero_sub_val);
    draw_cjk_12x12(&mut disp, &sub_str, 182, 102, true, TextAlign::Right, 1);

    // Horizontal Divider + 2x2 Spacious Telemetry Grid (Y: 122..189)
    disp.fill_rect(12, 122, 172, 1, true);
    disp.draw_dotted_vline(98, 126, 186, 2);
    disp.draw_dotted_hline(12, 184, 156, 2);
    disp.draw_crosshair(98, 156, 2);

    // Cell (0,0): 体感 16°C
    draw_cjk_12x12(&mut disp, &cfg.label_feels_like, 14, 134, true, TextAlign::Left, 1);
    draw_str_7x11(
        &mut disp,
        &format!("{}°C", scene.feels_like),
        90,
        135,
        true,
        1,
        TextAlign::Right,
    );

    // Cell (0,1): 湿度 78%
    draw_cjk_12x12(&mut disp, &cfg.label_humidity, 106, 134, true, TextAlign::Left, 1);
    draw_str_7x11(
        &mut disp,
        &format!("{}%", scene.humidity),
        182,
        135,
        true,
        1,
        TextAlign::Right,
    );

    // Cell (1,0): 东南风 3级
    draw_cjk_12x12(&mut disp, &scene.wind_dir, 14, 166, true, TextAlign::Left, 1);
    draw_cjk_12x12(&mut disp, "级", 90, 166, true, TextAlign::Right, 1);
    draw_str_7x11(
        &mut disp,
        &scene.wind_scale.to_string(),
        76,
        167,
        true,
        1,
        TextAlign::Right,
    );

    // Cell (1,1): 空气 [优] 28
    draw_cjk_12x12(&mut disp, &cfg.label_aqi, 106, 166, true, TextAlign::Left, 1);
    disp.draw_pill(136, 164, 18, 16, true, false);
    draw_cjk_12x12(&mut disp, &scene.aqi_grade, 145, 166, false, TextAlign::Center, 0);
    draw_str_7x11(
        &mut disp,
        &scene.aqi.to_string(),
        182,
        167,
        true,
        1,
        TextAlign::Right,
    );

    // --- Right Card: 24H Trend & Precipitation (X: 198, Y: 37, W: 198, H: 156) ---
    disp.draw_chamfer_card(198, 37, 198, 156, cfg.card_border_px, cfg.card_shadow_px);
    disp.fill_rect(200, 62, 194, 1, true);

    disp.draw_pill(206, 43, 28, 15, true, false);
    draw_micro_5x7(&mut disp, &cfg.trend_badge, 220, 47, false, 1, TextAlign::Center);
    draw_cjk_12x12(&mut disp, &cfg.trend_title, 238, 45, true, TextAlign::Left, 2);

    let rad_w = (measure_cjk_12(&scene.radar_summary, 1) + 10) as u32;
    let has_precip = scene.minute_bars.iter().any(|&b| b > 0.05);
    let rad_x = 388 - (rad_w as i32);
    disp.draw_pill(rad_x, 42, rad_w, 17, has_precip, false);
    draw_cjk_12x12(
        &mut disp,
        &scene.radar_summary,
        388 - (rad_w as i32) / 2,
        45,
        !has_precip,
        TextAlign::Center,
        1,
    );
    visible.push(scene.radar_summary.clone());

    // Spacious 5-Point Curve Area (X: 212..382, Y: 82..164)
    let (c_x0, c_y0, c_w, c_h) = (212_i32, 82_i32, 170_i32, 82_i32);
    let base_y = c_y0 + c_h;
    disp.fill_rect(c_x0, base_y, c_w as u32, 1, true);
    disp.draw_dotted_hline(c_x0, c_x0 + c_w, c_y0 + c_h / 2, 3);

    let max_pts = cfg.hourly_points.clamp(3, 7);
    let h_slice: Vec<&(String, i32)> = scene.hourly_points.iter().take(max_pts).collect();
    if h_slice.len() >= 2 {
        let t_min = h_slice.iter().map(|p| p.1).min().unwrap_or(0) - 1;
        let t_max = h_slice.iter().map(|p| p.1).max().unwrap_or(30) + 1;
        let t_span = (t_max - t_min).max(1) as f32;
        let step_x = 144_i32 / ((h_slice.len() as i32) - 1).max(1);

        let mut nodes = Vec::with_capacity(h_slice.len());
        for (i, (h_lbl, tv)) in h_slice.iter().enumerate() {
            let px = c_x0 + 12 + (i as i32) * step_x;
            let ratio = ((*tv - t_min) as f32) / t_span;
            let py = base_y - 10 - (ratio * ((c_h - 22) as f32)).round() as i32;
            nodes.push((px, py, h_lbl.as_str(), *tv));
        }

        for i in 0..(nodes.len() - 1) {
            let (x1, y1, _, _) = nodes[i];
            let (x2, y2, _, _) = nodes[i + 1];
            let dx = (x2 - x1).max(1);
            for x_cur in x1..=x2 {
                let y_top = y1 + ((x_cur - x1) * (y2 - y1)) / dx;
                for y_cur in (y_top + 3)..base_y {
                    if x_cur.rem_euclid(2) == 0 && y_cur.rem_euclid(2) == 0 {
                        disp.draw_pixel(x_cur, y_cur, true);
                    }
                }
            }
        }

        if has_precip {
            for (idx_b, &bval) in scene.minute_bars.iter().enumerate() {
                if bval > 0.02 {
                    let bx = c_x0 + 6 + (idx_b as i32) * 6;
                    let bh = ((bval * 14.0).round() as i32).max(2);
                    disp.fill_rect(bx, base_y - bh, 3, bh as u32, true);
                }
            }
        }

        for i in 0..(nodes.len() - 1) {
            disp.draw_line(nodes[i].0, nodes[i].1, nodes[i + 1].0, nodes[i + 1].1, 2, true);
        }

        for (px, py, h_lbl, tv) in nodes {
            disp.fill_rect(px - 3, py - 3, 7, 7, false);
            disp.stroke_rect(px - 2, py - 2, 5, 5, 1, true);
            disp.draw_pixel(px, py, true);

            let lbl_s = format!("{tv}°");
            let lw = measure_str_7x11(&lbl_s, 1);
            let lx = px - lw / 2;
            let ly = py - 15;
            disp.fill_rect(lx - 1, ly - 1, (lw + 2) as u32, 13, false);
            draw_str_7x11(&mut disp, &lbl_s, px, ly, true, 1, TextAlign::Center);

            disp.fill_rect(px, base_y + 1, 1, 3, true);
            let tm_clean = if h_lbl.ends_with('H') {
                format!("{}:00", h_lbl.trim_end_matches('H'))
            } else {
                h_lbl.to_owned()
            };
            draw_micro_5x7(&mut disp, &tm_clean, px, base_y + 6, true, 1, TextAlign::Center);
        }
    }

    // =========================================================================
    // ZONE 3: BOTTOM 4-DAY FORECAST GALLERY CARDS (Y: 199..295, H: 96px)
    // =========================================================================
    let f_days: Vec<&DailyForecastItem> = scene
        .daily_forecast
        .iter()
        .take(cfg.forecast_days.clamp(3, 5))
        .collect();
    let g_min = f_days.iter().map(|d| d.low).min().unwrap_or(0);
    let g_max = f_days.iter().map(|d| d.high).max().unwrap_or(30);
    let g_span = (g_max - g_min).max(1) as f32;

    let card_count = f_days.len().max(1) as i32;
    let card_gap = 6_i32;
    let card_w = (390 - (card_count - 1) * card_gap) / card_count;
    let card_h = 95_u32;

    for (idx, d) in f_days.iter().enumerate() {
        let cx = 4 + (idx as i32) * (card_w + card_gap);
        let cy = 199_i32;
        disp.draw_chamfer_card(
            cx,
            cy,
            card_w as u32,
            card_h,
            cfg.card_border_px,
            cfg.card_shadow_px,
        );

        // 1. Card Header
        let inv_hdr = idx == 0 && cfg.invert_today_header;
        if inv_hdr {
            disp.fill_rect(cx + 2, cy + 2, (card_w - 4) as u32, 20, true);
        } else {
            disp.fill_rect(cx + 2, cy + 21, (card_w - 4) as u32, 1, true);
        }
        draw_cjk_12x12(&mut disp, &d.day_cn, cx + 8, cy + 6, !inv_hdr, TextAlign::Left, 1);
        draw_micro_5x7(
            &mut disp,
            &d.date,
            cx + card_w - 8,
            cy + 9,
            !inv_hdr,
            1,
            TextAlign::Right,
        );

        // 2. 24x24 Bespoke Pixel-Art Weather Icon + 16x16 Condition Name
        draw_mini_weather_icon_24(&mut disp, d.icon, cx + 9, cy + 27);
        draw_cjk_16x16(&mut disp, &d.cond, cx + 41, cy + 31, true, TextAlign::Left, 2);

        // 3. Low ~ High Range + Floating Pill Bar
        draw_str_7x11(
            &mut disp,
            &format!("{}°", d.low),
            cx + 9,
            cy + 58,
            true,
            1,
            TextAlign::Left,
        );
        draw_str_7x11(&mut disp, "~", cx + card_w / 2, cy + 58, true, 1, TextAlign::Center);
        draw_str_7x11(
            &mut disp,
            &format!("{}°", d.high),
            cx + card_w - 9,
            cy + 58,
            true,
            1,
            TextAlign::Right,
        );

        let bx = cx + 9;
        let bw_bar = (card_w - 18) as u32;
        let by = cy + 76;
        let bh_bar = 7_u32;
        disp.draw_pill(bx, by, bw_bar, bh_bar, false, false);
        disp.fill_sparse_dots(bx + 2, by + 2, bw_bar - 4, bh_bar - 4, 2);

        let r0 = ((d.low - g_min) as f32 / g_span).clamp(0.0, 1.0);
        let r1 = ((d.high - g_min) as f32 / g_span).clamp(0.0, 1.0);
        let sx = bx + 2 + (r0 * ((bw_bar - 6) as f32)).round() as i32;
        let ex = bx + 2 + (r1 * ((bw_bar - 6) as f32)).round() as i32;
        let fw = (ex - sx + 2).max(6) as u32;
        disp.fill_rect(sx, by + 1, fw, bh_bar - 2, true);

        if idx == 0 {
            let rc = ((scene.temp_c - g_min) as f32 / g_span).clamp(0.0, 1.0);
            let px_cur = bx + 3 + (rc * ((bw_bar - 7) as f32)).round() as i32;
            disp.fill_rect(px_cur - 1, by + 2, 3, bh_bar - 4, false);
            disp.draw_pixel(px_cur, by + 3, true);
        }
    }

    (disp.pixels, visible)
}

