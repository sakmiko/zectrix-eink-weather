fn draw_micro_5x7(
    disp: &mut FrameDisplay,
    text: &str,
    x: i32,
    y: i32,
    on: bool,
    gap: i32,
    align: TextAlign,
) -> i32 {
    if text.is_empty() {
        return 0;
    }
    let chars: Vec<char> = text.chars().collect();
    let total_w = (chars.len() as i32) * 5 + ((chars.len() as i32) - 1) * gap;
    let mut cx = match align {
        TextAlign::Left => x,
        TextAlign::Center => x - total_w / 2,
        TextAlign::Right => x - total_w,
    };
    for ch in chars {
        if ch == ' ' {
            cx += 3 + gap;
            continue;
        }
        let rows = micro_pixel_glyph(ch);
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..5_i32 {
                if ((bits >> (4 - rx)) & 1) == 1 {
                    disp.draw_pixel(cx + rx, y + (ry as i32), on);
                }
            }
        }
        cx += 5 + gap;
    }
    total_w
}

impl OriginDimensions for FrameDisplay {
    fn size(&self) -> Size {
        Size::new(DISPLAY_WIDTH, DISPLAY_HEIGHT)
    }
}

impl DrawTarget for FrameDisplay {
    type Color = BinaryColor;
    type Error = Infallible;

    fn draw_iter<I>(&mut self, pixels: I) -> Result<(), Self::Error>
    where
        I: IntoIterator<Item = Pixel<Self::Color>>,
    {
        for Pixel(point, color) in pixels {
            self.draw_pixel(point.x, point.y, color == BinaryColor::On);
        }
        Ok(())
    }
}

struct FrameDisplay {
    pixels: Vec<u8>,
}

impl FrameDisplay {
    fn new() -> Self {
        Self {
            pixels: vec![255; (DISPLAY_WIDTH * DISPLAY_HEIGHT) as usize],
        }
    }

    #[inline]
    fn draw_pixel(&mut self, x: i32, y: i32, on: bool) {
        if x >= 0 && y >= 0 && (x as u32) < DISPLAY_WIDTH && (y as u32) < DISPLAY_HEIGHT {
            let index = (y as u32 * DISPLAY_WIDTH + x as u32) as usize;
            self.pixels[index] = if on { 0 } else { 255 };
        }
    }

    fn fill_rect(&mut self, x: i32, y: i32, w: u32, h: u32, on: bool) {
        for py in y..y.saturating_add(h as i32) {
            for px in x..x.saturating_add(w as i32) {
                self.draw_pixel(px, py, on);
            }
        }
    }

    fn stroke_rect(&mut self, x: i32, y: i32, w: u32, h: u32, thickness: u32, on: bool) {
        let t = thickness.min(w).min(h);
        let (t_i32, w_i32, h_i32) = (t as i32, w as i32, h as i32);
        self.fill_rect(x, y, w, t, on);
        self.fill_rect(x, y + h_i32 - t_i32, w, t, on);
        self.fill_rect(x, y, t, h, on);
        self.fill_rect(x + w_i32 - t_i32, y, t, h, on);
    }

    fn draw_chamfer_card(&mut self, x: i32, y: i32, w: u32, h: u32, border: u32, shadow: u32) {
        let (w_i32, h_i32, s_i32) = (w as i32, h as i32, shadow as i32);
        if shadow > 0 {
            self.fill_rect(x + s_i32, y + h_i32, w.saturating_sub(1), shadow, true);
            self.fill_rect(x + w_i32, y + s_i32, shadow, h.saturating_sub(1), true);
        }
        self.fill_rect(x, y, w, h, false);
        self.stroke_rect(x, y, w, h, border, true);
        for (cx, cy) in [
            (x, y),
            (x + w_i32 - 1, y),
            (x, y + h_i32 - 1),
            (x + w_i32 - 1, y + h_i32 - 1),
        ] {
            self.draw_pixel(cx, cy, false);
        }
    }

    fn draw_pill(&mut self, x: i32, y: i32, w: u32, h: u32, filled: bool, inverted: bool) {
        let (w_i32, h_i32) = (w as i32, h as i32);
        let fg = !inverted;
        let bg = inverted;
        if filled {
            self.fill_rect(x, y, w, h, fg);
        } else {
            self.fill_rect(x, y, w, h, bg);
            self.stroke_rect(x, y, w, h, 1, fg);
        }
        for (cx, cy) in [
            (x, y),
            (x + w_i32 - 1, y),
            (x, y + h_i32 - 1),
            (x + w_i32 - 1, y + h_i32 - 1),
        ] {
            self.draw_pixel(cx, cy, bg);
        }
    }

    fn fill_halftone(&mut self, x: i32, y: i32, w: u32, h: u32, step: i32) {
        let step = step.max(1);
        for py in y..y.saturating_add(h as i32) {
            for px in x..x.saturating_add(w as i32) {
                if (px + py).rem_euclid(step) == 0 {
                    self.draw_pixel(px, py, true);
                }
            }
        }
    }

    fn fill_sparse_dots(&mut self, x: i32, y: i32, w: u32, h: u32, pitch: i32) {
        let p = pitch.max(1);
        for py in y..y.saturating_add(h as i32) {
            for px in x..x.saturating_add(w as i32) {
                if px.rem_euclid(p) == 0 && py.rem_euclid(p) == 0 {
                    self.draw_pixel(px, py, true);
                }
            }
        }
    }

    fn draw_dotted_hline(&mut self, x0: i32, x1: i32, y: i32, step: i32) {
        let s = step.max(1);
        for x in x0..=x1 {
            if x.rem_euclid(s) == 0 {
                self.draw_pixel(x, y, true);
            }
        }
    }

    fn draw_dotted_vline(&mut self, x: i32, y0: i32, y1: i32, step: i32) {
        let s = step.max(1);
        for y in y0..=y1 {
            if y.rem_euclid(s) == 0 {
                self.draw_pixel(x, y, true);
            }
        }
    }

    fn draw_crosshair(&mut self, cx: i32, cy: i32, radius: i32) {
        for dx in -radius..=radius {
            self.draw_pixel(cx + dx, cy, true);
        }
        for dy in -radius..=radius {
            self.draw_pixel(cx, cy + dy, true);
        }
    }

    fn draw_line(&mut self, mut x0: i32, mut y0: i32, x1: i32, y1: i32, thickness: u32, on: bool) {
        let dx = (x1 - x0).abs();
        let dy = -(y1 - y0).abs();
        let sx = if x0 < x1 { 1 } else { -1 };
        let sy = if y0 < y1 { 1 } else { -1 };
        let mut err = dx + dy;
        let half = (thickness / 2) as i32;
        loop {
            if thickness <= 1 {
                self.draw_pixel(x0, y0, on);
            } else {
                self.fill_rect(x0 - half, y0 - half, thickness, thickness, on);
            }
            if x0 == x1 && y0 == y1 {
                break;
            }
            let e2 = 2 * err;
            if e2 >= dy {
                err += dy;
                x0 += sx;
            }
            if e2 <= dx {
                err += dx;
                y0 += sy;
            }
        }
    }
}

